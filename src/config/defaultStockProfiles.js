const CATALOG_FALLBACK_PROFILES = Object.fromEntries(
  STOCK_CATALOG.map((stock) => {
    const companyNameKo = stock.companyName || stock.ticker;
    const guidance = CATEGORY_GUIDANCE[stock.categoryName] || CATEGORY_GUIDANCE.ETF;
    const keywordText = stock.explorationKeywords.length > 0
      ? `<p>함께 살펴볼 주제: ${stock.explorationKeywords.join(", ")}</p>`
      : "";
    const riskText = stock.riskTags.length > 0
      ? `<p>확인할 상품 특성: ${stock.riskTags.join(", ")}</p>`
      : "";
    const content = `<p>${withTopicParticle(companyNameKo)} ${stock.categoryName} 분야에서 살펴볼 수 있는 ${stock.type === "ETF" ? "ETF" : "기업"}이에요.</p><p>${guidance}</p>${keywordText}${riskText}<p>이 설명은 회사를 처음 알아보는 데 도움을 주는 교육용 요약이며, 실제 투자 판단을 위한 추천은 아니에요.</p>`;
    return [stock.ticker, {
      ticker: stock.ticker,
      companyNameKo,
      category: stock.categoryName,
      title: `${companyNameKo}, 어떤 ${stock.type === "ETF" ? "상품" : "회사"}일까요?`,
      content,
    }];
  }),
);

export const DEFAULT_STOCK_PROFILES = Object.freeze(
  {
    ...CATALOG_FALLBACK_PROFILES,
    ...REVIEWED_STOCK_PROFILES,
  },
);

export const getDefaultStockProfile = (symbol) =>
  DEFAULT_STOCK_PROFILES[String(symbol || "").trim().toUpperCase()] || null;

export const getKoreanCompanyName = (symbol, fallback = "") =>
  getDefaultStockProfile(symbol)?.companyNameKo || fallback || String(symbol || "").trim().toUpperCase();
