const withTopicParticle = (value) => {
  const name = String(value || "").trim();
  const lastCharacter = name.charCodeAt(name.length - 1);
  const hasKoreanFinalConsonant =
    lastCharacter >= 0xac00 &&
    lastCharacter <= 0xd7a3 &&
    (lastCharacter - 0xac00) % 28 !== 0;
  return `${name}${hasKoreanFinalConsonant ? "은" : "는"}`;
};

